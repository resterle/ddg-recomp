#!/bin/sh
# Compiles port/src/unb/shaders/scene.glsl to SPIR-V for SDL GPU's Vulkan backend and writes
# port/src/unb/GraphicShadersSPV.h (checked in, so building the game needs no shader compiler).
# Needs glslangValidator (Arch: glslang, Debian: glslang-tools); spirv-val is used when present.
set -e
here=$(cd "$(dirname "$0")" && pwd)
unb=$here/../src/unb
src=$unb/shaders/scene.glsl
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out=$tmp/GraphicShadersSPV.h
{
    echo "// GraphicShadersSPV.h - SPIR-V builds of shaders/scene.glsl for SDL GPU on Vulkan."
    echo "// Generated by port/tools/build_spirv.sh; do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
} > "$out"
# name stage defines
while read -r name stage defs; do
    [ -n "$name" ] || continue
    args=""
    for d in $defs; do args="$args -D$d"; done
    glslangValidator -V --target-env vulkan1.0 -S "$stage" $args -o "$tmp/$name.spv" "$src" >"$tmp/log" 2>&1 ||
        { cat "$tmp/log"; exit 1; }
    if command -v spirv-val >/dev/null; then spirv-val "$tmp/$name.spv"; fi
    python3 - "$tmp/$name.spv" "$name" >> "$out" <<'EOF'
import struct, sys
data = open(sys.argv[1], 'rb').read()
words = struct.unpack('<%dI' % (len(data) // 4), data)
print('static const uint32_t %s[] = {' % sys.argv[2])
for i in range(0, len(words), 8):
    print('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
print('};')
EOF
done <<'LIST'
kSpvVSMain       vert VS_MAIN
kSpvVSMainFlat   vert VS_MAIN FLAT_COLOR
kSpvFSMain       frag FS_MAIN
kSpvFSMainFlat   frag FS_MAIN FLAT_COLOR
kSpvVSMesh       vert VS_MESH
kSpvVSMeshFlat   vert VS_MESH FLAT_COLOR
kSpvFSMesh       frag FS_MESH
kSpvFSMeshFlat   frag FS_MESH FLAT_COLOR
kSpvVSPresent    vert VS_PRESENT
kSpvFSPresent    frag FS_PRESENT
LIST
mv "$out" "$unb/GraphicShadersSPV.h"
echo "wrote $unb/GraphicShadersSPV.h"
