// Dispatch

// Direct table over the address range of all known functions: one load per indirect call
// (C++ virtual calls and function pointers are frequent) instead of a binary search.
static RecompFn *g_fast;
static uint32_t g_fastBase, g_fastN;

static void build_fast_table(void)
{
    g_fastBase = RT_TABLE[0].addr;
    g_fastN = RT_TABLE[RT_TABLE_N - 1].addr - g_fastBase + 1;
    g_fast = calloc(g_fastN, sizeof(RecompFn));
    for (int i = 0; i < RT_TABLE_N; i++) g_fast[RT_TABLE[i].addr - g_fastBase] = RT_TABLE[i].fn;
}

static inline RecompFn lookup(uint32_t a)
{
    uint32_t i = a - g_fastBase;
    return i < g_fastN ? g_fast[i] : NULL;
}

static void (*g_hostFn[128])(void);
static int g_hostFnN;

uint32_t rt_host_fn(void (*fn)(void))
{
    for (int i = 0; i < g_hostFnN; i++) if (g_hostFn[i] == fn) return RT_HOSTFN_BASE + 4u * i;
    if (g_hostFnN == 128) RT_Fatal("too many host functions", 0);
    g_hostFn[g_hostFnN] = fn;
    return RT_HOSTFN_BASE + 4u * g_hostFnN++;
}

void RT_CallAddr(uint32_t a)
{
    if (a >= RT_HOSTFN_BASE && a < RT_HOSTFN_BASE + 4u * g_hostFnN) {
        g_hostFn[(a - RT_HOSTFN_BASE) / 4]();
        return;
    }
    if (a >= RT_IMPORT_BASE && a < RT_IMPORT_BASE + 4u * RT_IMPORTS_N) {
        int i = (a - RT_IMPORT_BASE) / 4;
        if (!g_importFn[i]) RT_Fatal(RT_IMPORTS[i].name, a);
        g_importFn[i]();
        return;
    }
    RecompFn f = lookup(a);
    if (!f) {
        // remember it: build_game.py translates addresses listed in build/discovered.txt
        FILE *d = fopen("build/discovered.txt", "a");
        if (d) { fprintf(d, "%08x\n", a); fclose(d); }
        RT_Fatal("call to unknown address (added to build/discovered.txt)", a);
    }
    f();
}

static void print_guest_state(void)
{
    fprintf(stderr, "    eax=%08x ecx=%08x edx=%08x ebx=%08x esp=%08x ebp=%08x esi=%08x edi=%08x\n",
            R.eax, R.ecx, R.edx, R.ebx, R.esp, R.ebp, R.esi, R.edi);
    // best-effort backtrace: stack words that look like return addresses into the image's code
    fprintf(stderr, "    stack:");
    int n = 0;
    for (uint32_t p = R.esp; p < R.esp + 0x800 && n < 16; p += 4) {
        uint32_t v = RD32(p);
        if (v >= 0x401000 && v < 0x4b2000) { fprintf(stderr, " %08x", v); n++; }
    }
    fprintf(stderr, "\n");
    fflush(stderr);
}

void RT_Fatal(const char *what, uint32_t addr)
{
    fprintf(stderr, "\n*** recomp trap: %s (0x%08x) on thread %x\n", what, addr, t_self ? t_self->tid : 0);
    print_guest_state();
    _exit(1);
}

// Host crashes (SIGSEGV etc.): report where, with a host backtrace and the guest registers, so a
// crash on a device without a debugger can be located from log.txt (addr2line / nm on the binary).
static void crash_handler(int sig, siginfo_t *si, void *uc)
{
    void *pc = 0;
#if defined(__linux__) && defined(__aarch64__)
    pc = (void *)((ucontext_t *)uc)->uc_mcontext.pc;
#elif defined(__linux__) && defined(__x86_64__)
    pc = (void *)((ucontext_t *)uc)->uc_mcontext.gregs[REG_RIP];
#elif defined(__APPLE__) && defined(__aarch64__)
    pc = (void *)((ucontext_t *)uc)->uc_mcontext->__ss.__pc;
#endif
    fprintf(stderr, "\n*** crash: signal %d (%s) at address %p, pc %p, thread %x\n", sig, strsignal(sig), si->si_addr, pc,
            t_self ? t_self->tid : 0);
    Dl_info di;
    if (pc && dladdr(pc, &di))
        fprintf(stderr, "    pc in %s (%s+0x%lx), module base %p\n", di.dli_fname ? di.dli_fname : "?",
                di.dli_sname ? di.dli_sname : "?", di.dli_saddr ? (unsigned long)((char *)pc - (char *)di.dli_saddr) : 0,
                di.dli_fbase);
    if (MEM && (uint8_t *)si->si_addr >= MEM && (uint8_t *)si->si_addr < MEM + 0x100000000ull)
        fprintf(stderr, "    fault address is guest address 0x%08x\n", (unsigned)((uint8_t *)si->si_addr - MEM));
    void *bt[48];
    int n = backtrace(bt, 48);
    fprintf(stderr, "    host backtrace:\n");
    fflush(stderr);
    backtrace_symbols_fd(bt, n, 2);
    print_guest_state();
    signal(sig, SIG_DFL);
    _exit(128 + sig);
}

void rt_install_crash_handler(void)
{
    static char altstack[64 * 1024];            // also reports host stack overflows
    stack_t ss = { .ss_sp = altstack, .ss_size = sizeof(altstack) };
    sigaltstack(&ss, 0);
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_sigaction = crash_handler;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    int sigs[] = { SIGSEGV, SIGBUS, SIGILL, SIGFPE, SIGABRT };
    for (int i = 0; i < 5; i++) sigaction(sigs[i], &sa, 0);
}

// ---------------------------------------------------------------------------------------------
// RECOMP_PROFILE=<file>: CPU sampling profiler (Linux; the handhelds have no perf). SIGPROF after
// every millisecond of process CPU time records the running thread, its PC and (arm64) the link
// register, which names the caller of leaf functions such as memcpy; rt_profile_dump
// (at exit) writes the executable mappings, the thread names and the samples for
// tools/profile.py, which symbolises them.

#ifdef __linux__
#include <sys/syscall.h>
#include <sys/time.h>
enum { PROF_MAX = 1 << 20 };
static uint64_t *g_profPc, *g_profLr;
static uint32_t *g_profTid;
static uint32_t g_profN;

static void prof_handler(int sig, siginfo_t *si, void *ctx)
{
    (void)sig; (void)si;
    ucontext_t *uc = (ucontext_t *)ctx;
#if defined(__aarch64__)
    uint64_t pc = uc->uc_mcontext.pc, lr = uc->uc_mcontext.regs[30];
#elif defined(__x86_64__)
    uint64_t pc = (uint64_t)uc->uc_mcontext.gregs[REG_RIP], lr = 0;
#else
    uint64_t pc = 0, lr = 0;
#endif
    uint32_t i = __atomic_fetch_add(&g_profN, 1, __ATOMIC_RELAXED);
    if (i < PROF_MAX) { g_profPc[i] = pc; g_profLr[i] = lr; g_profTid[i] = (uint32_t)syscall(SYS_gettid); }
}

void rt_profile_start(void)
{
    if (!getenv("RECOMP_PROFILE")) return;
    g_profPc = malloc(PROF_MAX * sizeof(uint64_t));
    g_profLr = malloc(PROF_MAX * sizeof(uint64_t));
    g_profTid = malloc(PROF_MAX * sizeof(uint32_t));
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_sigaction = prof_handler;
    sa.sa_flags = SA_SIGINFO | SA_RESTART;
    sigaction(SIGPROF, &sa, 0);
    struct itimerval it = { { 0, 1000 }, { 0, 1000 } };
    setitimer(ITIMER_PROF, &it, 0);
}

void rt_profile_dump(void)
{
    const char *path = getenv("RECOMP_PROFILE");
    if (!path || !g_profPc) return;
    struct itimerval off;
    memset(&off, 0, sizeof(off));
    setitimer(ITIMER_PROF, &off, 0);
    FILE *f = fopen(path, "w");
    if (!f) return;
    char line[512];
    FILE *m = fopen("/proc/self/maps", "r");
    while (m && fgets(line, sizeof(line), m)) if (strstr(line, " r-xp ")) fprintf(f, "map %s", line);
    if (m) fclose(m);
    DIR *d = opendir("/proc/self/task");
    struct dirent *e;
    while (d && (e = readdir(d))) {
        if (e->d_name[0] == '.') continue;
        char p[300], name[64] = "";
        snprintf(p, sizeof(p), "/proc/self/task/%s/comm", e->d_name);
        FILE *c = fopen(p, "r");
        if (c) { if (fgets(name, sizeof(name), c)) name[strcspn(name, "\n")] = 0; fclose(c); }
        fprintf(f, "thread %s %s\n", e->d_name, name);
    }
    if (d) closedir(d);
    uint32_t n = g_profN < PROF_MAX ? g_profN : PROF_MAX;
    fprintf(f, "main %d\n", (int)getpid());
    for (uint32_t i = 0; i < n; i++)
        fprintf(f, "s %u %llx %llx\n", g_profTid[i], (unsigned long long)g_profPc[i], (unsigned long long)g_profLr[i]);
    fclose(f);
    fprintf(stderr, "profile: %u samples written to %s\n", n, path);
}
#else
void rt_profile_start(void) {}
void rt_profile_dump(void) {}
#endif

