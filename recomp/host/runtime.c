// ---------------------------------------------------------------------------------------------
// Threads and the global lock

#define MAX_MSG 256
#define RT_MAX_WAIT 64     // handles per WaitForMultipleObjects (MAXIMUM_WAIT_OBJECTS)
typedef struct { uint32_t msg, wparam, lparam; } Msg;

struct RtThread {
    pthread_t th;
    uint32_t tid;
    uint32_t handle;
    CPU cpu;
    uint8_t tib[0x40];
    uint32_t stackTop;
    uint32_t start, param;
    int suspended, finished;
    uint32_t exitCode;
    uint32_t lastError;
    uint32_t tls[64];
    Msg queue[MAX_MSG];
    int qhead, qcount;
    jmp_buf exitJmp;
    // waiting (rt_wait_objs / rt_wait): woken by signals for one of waitObj, or by any signal
    // with waitAny; each thread sleeps on its own condition variable
    pthread_cond_t cv;
    const void *waitObj[RT_MAX_WAIT];
    int nWait, waitAny;
    struct RtThread *next;
};

static pthread_mutex_t g_gil = PTHREAD_MUTEX_INITIALIZER;
static __thread RtThread *t_self;
static RtThread *g_threads;
static uint32_t g_nextTid = 0x100;
static uint32_t g_nextStack = RT_STACK_BASE;

RtThread *rt_self(void) { return t_self; }
uint32_t rt_thread_id(RtThread *t) { return t ? t->tid : 0; }

// Instructions executed while holding the lock, i.e. by game code and the natives it calls
// (diagnostics; macOS only).
#ifdef __APPLE__
extern int thread_selfcounts(int type, void *buf, size_t nbytes);
uint64_t rt_thread_instructions(void)
{
    uint64_t c[2] = {0, 0};
    thread_selfcounts(1, c, sizeof(c));
    return c[0];
}
#else
uint64_t rt_thread_instructions(void) { return 0; }
#endif
uint64_t RT_SAVES;                                  /* RT_COUNT_SAVES builds */
static uint64_t g_lockedInstr;
static __thread uint64_t t_instrStart;
uint64_t rt_locked_instructions(void) { return g_lockedInstr; }

static void save_state(void)
{
    g_lockedInstr += rt_thread_instructions() - t_instrStart;
    t_self->cpu = R;
    memcpy(t_self->tib, MEM + RT_FS_BASE, sizeof(t_self->tib));
}

static void restore_state(void)
{
    t_instrStart = rt_thread_instructions();
    R = t_self->cpu;
    memcpy(MEM + RT_FS_BASE, t_self->tib, sizeof(t_self->tib));
}

void rt_leave(void)
{
    save_state();
    pthread_mutex_unlock(&g_gil);
}

void rt_enter(void)
{
    pthread_mutex_lock(&g_gil);
    restore_state();
}

// Waiting (lock held): the thread sleeps on its own condition variable until a signal for one
// of `objs` (rt_signal_obj) or any signal (rt_signal) arrives, or `ms` pass. Returns 0 on
// timeout. Callers re-check their condition (wake-ups may be spurious). One shared condition
// variable with broadcasts woke every waiting guest thread for every SetEvent and
// LeaveCriticalSection, each then taking the runtime lock to go back to sleep: about half of the
// guest threads' CPU time went into futex calls (profile on the PC), and the running thread
// waited for the lock meanwhile.
static int wait_self(uint32_t ms)
{
    RtThread *t = t_self;
    int ok = 1;
    if (ms == 0xffffffffu) {
        pthread_cond_wait(&t->cv, &g_gil);
    } else {
        struct timespec ts;
        clock_gettime(CLOCK_REALTIME, &ts);
        ts.tv_sec += ms / 1000;
        ts.tv_nsec += (long)(ms % 1000) * 1000000L;
        if (ts.tv_nsec >= 1000000000L) { ts.tv_sec++; ts.tv_nsec -= 1000000000L; }
        ok = pthread_cond_timedwait(&t->cv, &g_gil, &ts) != ETIMEDOUT;
    }
    return ok;
}

int rt_wait_objs(const void *const *objs, int n, uint32_t ms)
{
    RtThread *t = t_self;
    save_state();
    if (n > RT_MAX_WAIT || n <= 0) { t->waitAny = 1; n = 0; }
    for (int i = 0; i < n; i++) t->waitObj[i] = objs[i];
    t->nWait = n;
    int ok = wait_self(ms);
    t->nWait = 0;
    t->waitAny = 0;
    restore_state();
    return ok;
}

int rt_wait(uint32_t ms) { return rt_wait_objs(NULL, 0, ms); }

void rt_signal_obj(const void *obj)
{
    for (RtThread *t = g_threads; t; t = t->next) {
        int hit = t->waitAny;
        for (int i = 0; i < t->nWait && !hit; i++) hit = t->waitObj[i] == obj;
        if (hit) pthread_cond_signal(&t->cv);
    }
}

void rt_signal(void)
{
    for (RtThread *t = g_threads; t; t = t->next)
        if (t->waitAny || t->nWait) pthread_cond_signal(&t->cv);
}
// Host threads that are not emulated threads (sound mixer) take the runtime lock around calls
// that touch shared runtime state (e.g. rt_event_set).
void rt_lock_host(void) { pthread_mutex_lock(&g_gil); }
void rt_unlock_host(void) { pthread_mutex_unlock(&g_gil); }

static void init_tib(RtThread *t)
{
    memset(t->tib, 0, sizeof(t->tib));
    uint32_t v;
    v = 0xffffffffu; memcpy(t->tib + 0x00, &v, 4);                 // SEH chain end
    v = t->stackTop; memcpy(t->tib + 0x04, &v, 4);                 // stack base
    v = t->stackTop - RT_STACK_SIZE; memcpy(t->tib + 0x08, &v, 4); // stack limit
    v = RT_FS_BASE; memcpy(t->tib + 0x18, &v, 4);                  // self
    v = 1; memcpy(t->tib + 0x20, &v, 4);                           // process id
    memcpy(t->tib + 0x24, &t->tid, 4);                             // thread id
}

static RtThread *new_thread(void)
{
    RtThread *t = calloc(1, sizeof(RtThread));
    t->tid = g_nextTid++;
    t->stackTop = g_nextStack + RT_STACK_SIZE - 0x100;
    g_nextStack += RT_STACK_SIZE;
    t->cpu.esp = t->stackTop;
    t->cpu.cw = 0x027f;
    init_tib(t);
    pthread_cond_init(&t->cv, NULL);
    t->next = g_threads;
    g_threads = t;
    return t;
}

uint32_t rt_call(uint32_t addr, int nargs, const uint32_t *args)
{
    uint32_t esp = R.esp;
    for (int i = nargs - 1; i >= 0; i--) { R.esp -= 4; WR32(R.esp, args[i]); }
    R.esp -= 4;
    WR32(R.esp, 0);         // sentinel return address (never used: returns go back to C)
    RT_CallAddr(addr);
    uint32_t eax = R.eax;
    R.esp = esp;            // cdecl or stdcall: the frame is gone either way
    return eax;
}

// Game threads run at user-interactive QoS so macOS keeps them on the performance cores (the
// 60 Hz sleep/wake rhythm otherwise lets the scheduler move them to the efficiency cores).
static void set_thread_qos(void)
{
#ifdef __APPLE__
    pthread_set_qos_class_self_np(QOS_CLASS_USER_INTERACTIVE, 0);
#endif
}

static void *thread_main(void *arg)
{
    set_thread_qos();
    RtThread *t = arg;
    t_self = t;
    pthread_mutex_lock(&g_gil);
    while (t->suspended) {
        t->waitObj[0] = &t->suspended;
        t->nWait = 1;
        pthread_cond_wait(&t->cv, &g_gil);
        t->nWait = 0;
    }
    restore_state();
    if (!setjmp(t->exitJmp)) {
        uint32_t p = t->param;
        t->exitCode = rt_call(t->start, 1, &p);
    }
    t->finished = 1;
    rt_signal_obj(t);                               // waits on the thread's handle
    pthread_mutex_unlock(&g_gil);
    return NULL;
}

uint32_t rt_create_thread(uint32_t start, uint32_t param, int suspended, uint32_t *tid)
{
    RtThread *t = new_thread();
    t->start = start;
    t->param = param;
    t->suspended = suspended;
    t->handle = rt_handle_new(H_THREAD, t);
    if (tid) *tid = t->tid;
    pthread_attr_t a;
    pthread_attr_init(&a);
    pthread_attr_setstacksize(&a, 8u << 20);      // native stack for deep recursion in translated code
    pthread_create(&t->th, &a, thread_main, t);
    return t->handle;
}

// CPU time of a guest thread given its handle, in ns (0 if unknown or finished; Linux only).
uint64_t rt_thread_cpu_ns(uint32_t handle)
{
#ifdef __linux__
    RtThread *t = rt_handle_get(handle, H_THREAD);
    clockid_t c;
    struct timespec ts;
    if (!t || t->finished || pthread_getcpuclockid(t->th, &c) || clock_gettime(c, &ts)) return 0;
    return (uint64_t)ts.tv_sec * 1000000000ull + (uint64_t)ts.tv_nsec;
#else
    (void)handle;
    return 0;
#endif
}

void rt_thread_resume(RtThread *t) { t->suspended = 0; rt_signal_obj(&t->suspended); }
int rt_thread_finished(RtThread *t) { return t->finished; }
uint32_t rt_thread_exitcode(RtThread *t) { return t->exitCode; }
void rt_thread_exit(uint32_t code) { t_self->exitCode = code; longjmp(t_self->exitJmp, 1); }
uint32_t *rt_tls(void) { return t_self->tls; }
uint32_t *rt_last_error(void) { return &t_self->lastError; }

RtThread *rt_thread_by_id(uint32_t tid)
{
    for (RtThread *t = g_threads; t; t = t->next)
        if (t->tid == tid) return t;
    return NULL;
}

// Per-thread message queues (PostThreadMessage / GetMessage / PeekMessage)
void rt_message_post(uint32_t tid, uint32_t msg, uint32_t wparam, uint32_t lparam)
{
    RtThread *t = rt_thread_by_id(tid);
    if (!t || t->qcount == MAX_MSG) return;
    t->queue[(t->qhead + t->qcount++) % MAX_MSG] = (Msg){msg, wparam, lparam};
    rt_signal_obj(t->queue);
}

int rt_message_get(uint32_t *msg, uint32_t *wparam, uint32_t *lparam, int remove, int wait)
{
    RtThread *t = t_self;
    while (!t->qcount) {
        if (!wait) return 0;
        const void *q = t->queue;
        rt_wait_objs(&q, 1, 0xffffffffu);
    }
    Msg m = t->queue[t->qhead];
    if (remove) { t->qhead = (t->qhead + 1) % MAX_MSG; t->qcount--; }
    *msg = m.msg; *wparam = m.wparam; *lparam = m.lparam;
    return 1;
}

