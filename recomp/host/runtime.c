// Startup

// The exe as the translated code expects it (recomp/exepatch.py): DDGModernizer's patch sites
// (build/game/exe_info.c) are set to the values the build used, whether the file is the plain
// unprotected perfect.exe or one DDGModernizer already patched; then the image must have the
// hash the build recorded.
typedef struct { uint32_t off, len; const uint8_t *orig, *data, *mask; uint32_t origLen; } RtExePatch;
extern const RtExePatch rt_exe_patches[];
extern const int rt_exe_npatches;
extern const uint64_t rt_exe_hash;

typedef struct { uint32_t vs, va, rs, ra; char name[9]; } ExeSection;

// Section table, or -1 if the file is not a PE image (bounds checked).
static int exe_sections(const uint8_t *d, long size, ExeSection *sec, int max)
{
    if (size < 0x40 || d[0] != 'M' || d[1] != 'Z') return -1;
    uint32_t pe; memcpy(&pe, d + 0x3c, 4);
    if ((uint64_t)pe + 24 > (uint64_t)size || memcmp(d + pe, "PE\0\0", 4)) return -1;
    uint16_t nsec, optsz;
    memcpy(&nsec, d + pe + 6, 2); memcpy(&optsz, d + pe + 20, 2);
    if (nsec > max || (uint64_t)pe + 24 + optsz + 40u * nsec > (uint64_t)size) return -1;
    for (int i = 0; i < nsec; i++) {
        const uint8_t *s = d + pe + 24 + optsz + 40 * i;
        memcpy(sec[i].name, s, 8); sec[i].name[8] = 0;
        memcpy(&sec[i].vs, s + 8, 4); memcpy(&sec[i].va, s + 12, 4);
        memcpy(&sec[i].rs, s + 16, 4); memcpy(&sec[i].ra, s + 20, 4);
        uint32_t n = sec[i].rs < sec[i].vs || !sec[i].vs ? sec[i].rs : sec[i].vs;
        if ((uint64_t)sec[i].ra + n > (uint64_t)size) return -1;
    }
    return nsec;
}

// Reads and patches the exe; *status is one of RT_EXE_*. The buffer (malloc) only when OK.
static uint8_t *read_exe(const char *exe, long *psize, int *status)
{
    FILE *f = fopen(exe, "rb");
    if (!f) { *status = RT_EXE_MISSING; return NULL; }
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint8_t *d = size > 0 ? malloc(size) : NULL;
    if (!d || fread(d, 1, size, f) != (size_t)size) { fclose(f); free(d); *status = RT_EXE_NOT_PE; return NULL; }
    fclose(f);
    ExeSection sec[32];
    int nsec = exe_sections(d, size, sec, 32);
    *status = RT_EXE_NOT_PE;
    if (nsec < 0) { free(d); return NULL; }
    for (int i = 0; i < nsec; i++)
        if (!strcmp(sec[i].name, "stxt774") || !strcmp(sec[i].name, "stxt371")) { *status = RT_EXE_SAFEDISC; free(d); return NULL; }
    for (int i = 0; i < rt_exe_npatches; i++) {
        const RtExePatch *p = &rt_exe_patches[i];
        int ok = (uint64_t)p->off + p->len <= (uint64_t)size;
        if (ok && memcmp(d + p->off, p->orig, p->origLen)) {
            for (uint32_t k = 0; k < p->len && ok; k++)
                ok = !p->mask[k] || d[p->off + k] == p->data[k];
        }
        if (!ok) { *status = RT_EXE_UNKNOWN; free(d); return NULL; }
        memcpy(d + p->off, p->data, p->len);
    }
    uint64_t h = 0xcbf29ce484222325ull;                // FNV-1a 64, as exepatch.image_hash
    for (int i = 0; i < nsec; i++) {
        uint32_t n = sec[i].rs < sec[i].vs || !sec[i].vs ? sec[i].rs : sec[i].vs;
        for (uint32_t k = 0; k < n; k++) h = (h ^ d[sec[i].ra + k]) * 0x100000001b3ull;
    }
    if (h != rt_exe_hash) { *status = RT_EXE_OTHER_BUILD; free(d); return NULL; }
    *status = RT_EXE_OK;
    *psize = size;
    return d;
}

int rt_check_exe(const char *exe)
{
    long size;
    int status;
    free(read_exe(exe, &size, &status));
    return status;
}

static int load_image(const char *exe)
{
    long size;
    int status;
    uint8_t *d = read_exe(exe, &size, &status);
    if (!d) { fprintf(stderr, "%s: unusable exe (status %d)\n", exe, status); return 0; }
    ExeSection sec[32];
    int nsec = exe_sections(d, size, sec, 32);
    uint32_t pe, base, hdrsize;
    memcpy(&pe, d + 0x3c, 4);
    memcpy(&base, d + pe + 24 + 28, 4);
    memcpy(&hdrsize, d + pe + 24 + 60, 4);
    memcpy(MEM + base, d, hdrsize < size ? hdrsize : size);
    for (int i = 0; i < nsec; i++) {
        uint32_t n = sec[i].rs < sec[i].vs || !sec[i].vs ? sec[i].rs : sec[i].vs;
        memcpy(MEM + base + sec[i].va, d + sec[i].ra, n);
    }
    free(d);
    return 1;
}

// The fixed guest address range must be reserved before anything else claims address space:
// on macOS the GPU driver reserves gigabytes at a random place once a window exists. main() calls
// this first thing; rt_init only checks.
static int g_guestReserved;
int rt_reserve_guest_memory(void)
{
#ifdef RT_MEM_BASE
    if (g_guestReserved) return 1;
    uint8_t *m = NULL;
    for (int tries = 0; tries < 20 && m != (uint8_t *)(uintptr_t)RT_MEM_BASE; tries++) {
        if (tries) usleep(100000);
        m = rt_map_guest_memory(RT_MEM_BASE);
    }
    g_guestReserved = m == (uint8_t *)(uintptr_t)RT_MEM_BASE;
    return g_guestReserved;
#else
    return 1;
#endif
}

int rt_init(const char *exe, const char *gameDir)
{
#ifdef RT_MEM_BASE
    // a previous instance may still be releasing its mappings (seen right after exit on macOS)
    if (!rt_reserve_guest_memory()) {
        fprintf(stderr, "cannot reserve the emulated memory at %p; rebuild with another MEMBASE\n",
                (void *)(uintptr_t)RT_MEM_BASE);
#ifdef __APPLE__
        // what is in the way (base - 4 GB alias .. base + 4 GB)
        mach_vm_address_t a = RT_MEM_BASE - RT_GUEST_ALIAS;
        while (a < RT_MEM_BASE + RT_GUEST_SIZE) {
            mach_vm_size_t size = 0;
            vm_region_basic_info_data_64_t info;
            mach_msg_type_number_t cnt = VM_REGION_BASIC_INFO_COUNT_64;
            mach_port_t obj;
            if (mach_vm_region(mach_task_self(), &a, &size, VM_REGION_BASIC_INFO_64, (vm_region_info_t)&info, &cnt, &obj) != KERN_SUCCESS ||
                a >= RT_MEM_BASE + RT_GUEST_SIZE) break;
            fprintf(stderr, "  in the way: %llx-%llx prot %d\n", (unsigned long long)a, (unsigned long long)(a + size), info.protection);
            a += size;
        }
#endif
        return 0;
    }
#else
    MEM = rt_map_guest_memory(0);
    if (!MEM) { fprintf(stderr, "cannot reserve the emulated memory\n"); return 0; }
#endif
    build_fast_table();
    set_thread_qos();                               // the main thread runs the vsync ticks
    snprintf(g_gameDir, sizeof(g_gameDir), "%s", gameDir);
    if (!load_image(exe)) { fprintf(stderr, "cannot load %s\n", exe); return 0; }
    rt_win32_init();
    g_importFn = calloc(RT_IMPORTS_N, sizeof(RecompFn));
    int missing = 0;
    for (int i = 0; i < RT_IMPORTS_N; i++) {
        WR32(RT_IMPORTS[i].iat, RT_IMPORT_BASE + 4u * i);
        g_importFn[i] = rt_import(RT_IMPORTS[i].name);
        missing += !g_importFn[i];
    }
    fprintf(stderr, "recomp: %d imports, %d not implemented (trap if called)\n", RT_IMPORTS_N, missing);
    // the calling thread becomes the emulated main thread
    t_self = new_thread();
    t_self->handle = rt_handle_new(H_THREAD, t_self);
    pthread_mutex_lock(&g_gil);
    restore_state();
    return 1;
}

// An emulated thread whose body is native code (multimedia timers): holds the lock while the
// body runs, like any other emulated thread.
typedef struct { void *(*fn)(void *); void *arg; RtThread *t; } NativeStart;
static void *native_thread_main(void *p)
{
    set_thread_qos();
    NativeStart s = *(NativeStart *)p;
    free(p);
    t_self = s.t;
    pthread_mutex_lock(&g_gil);
    restore_state();
    s.fn(s.arg);
    t_self->finished = 1;
    rt_signal_obj(t_self);
    pthread_mutex_unlock(&g_gil);
    return NULL;
}

uint32_t rt_create_native_thread(void *(*fn)(void *), void *arg)
{
    RtThread *t = new_thread();
    t->handle = rt_handle_new(H_THREAD, t);
    NativeStart *s = malloc(sizeof(NativeStart));
    s->fn = fn; s->arg = arg; s->t = t;
    pthread_create(&t->th, NULL, native_thread_main, s);
    return t->handle;
}

void RT_StackFault(uint32_t site, uint32_t callee, uint32_t expected, uint32_t actual)
{
    char msg[160];
    snprintf(msg, sizeof(msg), "stack imbalance after call at %08x to %08x: esp %08x, expected %08x",
             site, callee, actual, expected);
    RT_Fatal(msg, callee);
}
