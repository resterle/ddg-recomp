// Handles

#define MAX_HANDLES 4096
static struct { int kind; void *obj; } g_handles[MAX_HANDLES];

uint32_t rt_handle_new(int kind, void *obj)
{
    for (int i = 1; i < MAX_HANDLES; i++)
        if (!g_handles[i].kind) { g_handles[i].kind = kind; g_handles[i].obj = obj; return 0x1000 + 4u * i; }
    RT_Fatal("out of handles", 0);
    return 0;
}

void *rt_handle_get(uint32_t h, int kind)
{
    uint32_t i = (h - 0x1000) / 4;
    if (h < 0x1000 || i >= MAX_HANDLES || !g_handles[i].kind) return NULL;
    if (kind && g_handles[i].kind != kind) return NULL;
    return g_handles[i].obj;
}

int rt_handle_kind(uint32_t h)
{
    uint32_t i = (h - 0x1000) / 4;
    return (h >= 0x1000 && i < MAX_HANDLES) ? g_handles[i].kind : H_NONE;
}

void rt_handle_close(uint32_t h)
{
    uint32_t i = (h - 0x1000) / 4;
    if (h >= 0x1000 && i < MAX_HANDLES) { g_handles[i].kind = 0; g_handles[i].obj = NULL; }
}

