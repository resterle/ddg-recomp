// "C:\Program Files\...\perfect\cddata\x.dat", "host0:cddata/x.dat", "cddata\x.dat" -> host path
// Windows file names are case-insensitive and the game asks for names whose case differs from
// the files on disk (e.g. "BGM22.INT" for "bgm22.int"). On case-sensitive file systems each
// path component after `keep` bytes is matched against the directory listing when the exact
// name does not exist. Missing components stay as given (new files keep the game's spelling).
static void rt_fix_case(char *path, int keep)
{
#ifdef __APPLE__
    (void)path; (void)keep;     // APFS/HFS+ default volumes are case-insensitive
#else
    struct stat st;
    if (stat(path, &st) == 0) return;
    char *p = path + keep;
    while (*p == '/') p++;
    while (*p) {
        char *slash = strchr(p, '/');
        if (slash) *slash = 0;
        if (stat(path, &st) != 0) {
            // look for a case-insensitive match of this component in its parent directory
            char *base = strrchr(path, '/');
            *base = 0;
            DIR *d = opendir(base == path ? "/" : path);
            *base = '/';
            int found = 0;
            if (d) {
                struct dirent *e;
                while ((e = readdir(d))) {
                    if (!strcasecmp(e->d_name, base + 1) && strlen(e->d_name) == strlen(base + 1)) {
                        memcpy(base + 1, e->d_name, strlen(e->d_name));
                        found = 1;
                        break;
                    }
                }
                closedir(d);
            }
            if (!found) { if (slash) *slash = '/'; return; }
        }
        if (!slash) break;
        *slash = '/';
        p = slash + 1;
    }
#endif
}

void rt_map_path(const char *win, char *host, int max)
{
    char tmp[1024];
    int n = 0;
    for (const char *p = win; *p && n < (int)sizeof(tmp) - 1; p++) tmp[n++] = *p == '\\' ? '/' : *p;
    tmp[n] = 0;
    const char *rel = tmp;
    if (!strncmp(rel, "host0:", 6)) rel += 6;
    else if (n >= 2 && rel[1] == ':') {
        rel += 2;
        while (*rel == '/') rel++;
        // "C:\AppData" (SHGetPathFromIDListA) is the per-user data directory: memory card saves
        if (g_appDataDir[0] && !strncasecmp(rel, "AppData", 7) && (rel[7] == '/' || !rel[7])) {
            snprintf(host, max, "%s%s", g_appDataDir, rel + 7);
            rt_fix_case(host, (int)strlen(g_appDataDir));
            return;
        }
        // strip the fake install directory GetModuleFileName reported ("/perfect/")
        const char *k = strstr(rel, "/perfect/");
        rel = k ? k + 9 : rel;
    }
    while (*rel == '/') rel++;
    snprintf(host, max, "%s/%s", g_gameDir, rel);
    rt_fix_case(host, (int)strlen(g_gameDir));
}

